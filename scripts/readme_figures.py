def save(fig, name):
    fig.savefig(OUT / f"{name}.svg", bbox_inches="tight", metadata={"Date": None})
    fig.savefig(OUT / f"{name}.png", bbox_inches="tight", dpi=144)
    plt.close(fig)
    print("wrote", name, (OUT / f"{name}.svg").stat().st_size, (OUT / f"{name}.png").stat().st_size)


CELL = re.compile(r"([\d.]+)% \[([\d.]+)%, ([\d.]+)%\] \(n=([\d,]+)")


def cell(s):
    m = CELL.search(s)
    return (float(m[1]) / 100, float(m[2]) / 100, float(m[3]) / 100, int(m[4].replace(",", ""))) if m else None


def md_table(path, header_start):
    """Rows of the first markdown table whose header line starts with header_start, as lists of cells."""
    lines = (REP / path).read_text().splitlines()
    i = next(k for k, l in enumerate(lines) if l.startswith(header_start))
    rows = []
    for l in lines[i + 2:]:
        if not l.startswith("|"):
            break
        rows.append([c.strip() for c in l.strip("|").split("|")])
    return [c.strip() for c in lines[i].strip("|").split("|")], rows


def section(path, title):
    s = (REP / path).read_text()
    return s.split(title, 1)[1]


def bars_h(ax, labels, vals, colors):
    y = range(len(labels))[::-1]
    for yi, v, col in zip(y, vals, colors):
        ax.barh(yi, v[0] * 100, color=col, height=0.62)
        ax.errorbar(v[0] * 100, yi, xerr=[[(v[0] - v[1]) * 100], [(v[2] - v[0]) * 100]], fmt="none", ecolor=INK,
                    capsize=3, lw=1.2, zorder=3)
        ax.text(v[2] * 100 + 1.2, yi, f"{v[0] * 100:.1f}%  (n={v[3]:,})", va="center", fontsize=9.5)
    ax.set_yticks(list(y), labels)
    ax.grid(axis="y", visible=False)


