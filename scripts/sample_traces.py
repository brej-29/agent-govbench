"""docs/sample_traces.md: one attack and one benign scenario, full trace under each pilot configuration."""
import json
from agent_govbench.report_runs import latest
from agent_govbench.scenarios import load

S = {s["scenario_id"]: s for s in load()}
runs = latest("pilot")
by = {}
for t in runs:
    by.setdefault(t["scenario_id"], {})[t["config"]] = t
att = next(sid for sid, d in by.items() if "G0" in d and d["G0"]["is_attack"] and d["G0"]["eval"]["attack_success"] and len(d) == 4)
ben = next(sid for sid, d in sorted(by.items()) if "G0" in d and not d["G0"]["is_attack"] and S[sid]["vector"] == "none" and len(d) == 4
           and d["G0"]["eval"]["benign_completed"] and any(x["kind"] == "call" for x in d["G0"]["steps"]))
out = ["# Sample traces (pilot, policy-in-prompt agent, standard tier)", "",
       "Generated by scripts/sample_traces.py from data/runs/pilot. Full raw traces (events, usage, guard logs) are in traces/pilot/ in the bucket.", ""]
for kind, sid in (("Attack", att), ("Benign", ben)):
    s = S[sid]
    out += [f"## {kind}: {sid}", f"- category: {s['category']}; technique: {s['technique']}; principal: {s['principal']['role']}",
            f"- success check: `{json.dumps(s['attack_check'])}`", ""]
    for cfg in ("G0", "G1", "G2p", "G6"):
        t = by[sid][cfg]
        out.append(f"### {cfg}  (latency {t['latency_s']} s incl. quota wait, agent USD {t['cost']['agent']['usd']:.4f}, eval {json.dumps(t['eval'])})")
        for x in t["steps"]:
            if x["kind"] == "user":
                out.append(f"- USER: {x['text']}")
            elif x["kind"] == "call":
                out.append(f"- CALL `{x['name']}({json.dumps(x['arguments'], ensure_ascii=False)})`")
            elif x["kind"] == "response":
                out.append(f"- RESULT `{json.dumps(x['response'], ensure_ascii=False)[:300]}`")
            else:
                out.append(f"- AGENT: {x['text'][:400]}")
        for g in t["guard_log"]:
            out.append(f"- GUARD {g['config']} stage={g['stage']} verdict={g['verdict']} latency_ms={g.get('latency_ms')} "
                       f"{('rule=' + str(g.get('rule'))) if g['config'] == 'G2p' else ''}{('findings=' + json.dumps(g.get('findings'))) if g['config'] == 'G1' else ''}"
                       f"{('reason=' + str(g.get('reason'))) if g['config'] == 'G6' else ''}")
        out.append("")
open("docs/sample_traces.md", "w").write("\n".join(out).replace("\u2014", "-"))
print(att, ben)
